using LatticeDiracOperators
using Test

const _Rhmc = LatticeDiracOperators.Rhmc
const _AlgRemez = LatticeDiracOperators.AlgRemez

function _rhmc_max_relative_error(coefficients, power; low=0.0004, high=64)
    f = _AlgRemez.fittedfunction(coefficients)
    xs = exp.(range(log(low), log(high), length=500))
    return maximum(abs(f(x) / x^power - 1) for x in xs)
end

@testset "Concurrent AlgRemez calls preserve caller files" begin
    mktempdir() do directory
        cd(directory) do
            write("approx.dat", "caller approximation\n")
            write("error.dat", "caller error\n")
            powers = (1//3, 2//3)
            tasks = map(powers) do power
                @async _Rhmc.RHMC(power; n=8, lambda_low=0.05, lambda_high=20)
            end
            results = fetch.(tasks)
            for (power, rhmc) in zip(powers, results)
                @test _rhmc_max_relative_error(rhmc.coeffs, power; low=0.05, high=20) < 1e-6
                @test _rhmc_max_relative_error(rhmc.coeffs_inverse, -power; low=0.05, high=20) < 1e-6
            end
            @test read("approx.dat", String) == "caller approximation\n"
            @test read("error.dat", String) == "caller error\n"
            @test sort(readdir()) == ["approx.dat", "error.dat"]
        end
    end
end

@testset "RHMC coefficient tables" begin
    tabulated = (
        (1, 2, 10), (3, 8, 10), (5, 8, 10), (7, 8, 10), (3, 4, 10),
        (1, 4, 10), (1, 8, 10), (-1, 2, 10), (-1, 4, 10), (-1, 8, 10),
        (3, 16, 15), (5, 16, 15), (7, 16, 15), (1, 16, 15), (3, 8, 15),
        (1, 4, 15), (1, 8, 15), (-1, 4, 15), (-1, 8, 15),
    )
    for (y, z, n) in tabulated
        rhmc = _Rhmc.RHMC(y, z; n)
        tolerance = n == 10 ? 1e-5 : 1e-7
        @test _rhmc_max_relative_error(rhmc.coeffs, y / z) < tolerance
        @test _rhmc_max_relative_error(rhmc.coeffs_inverse, -y / z) < tolerance
    end
end

@testset "RHMC coefficients from AlgRemez" begin
    # Not tabulated: the coefficients are generated by the AlgRemez binary.
    rhmc = _Rhmc.RHMC(1, 3; n=8, lambda_low=0.05, lambda_high=20)
    @test _rhmc_max_relative_error(rhmc.coeffs, 1 / 3; low=0.05, high=20) < 1e-6
    @test _rhmc_max_relative_error(rhmc.coeffs_inverse, -1 / 3; low=0.05, high=20) < 1e-6
    for y in (1, -1)
        rhmc = _Rhmc.RHMC(y, 2; n=15)
        @test _rhmc_max_relative_error(rhmc.coeffs, y / 2) < 1e-7
        @test _rhmc_max_relative_error(rhmc.coeffs_inverse, -y / 2) < 1e-7
    end
end
